//! 1行のテキストに対する一致の判定。

/// 1行のテキストに対する一致の判定。**照合の中身はここより外にある**。
///
/// 🔑 中核は「どう一致させるか」を知らない。固定文字列は
/// [`crate::fixed_string::FixedString`] が、正規表現はバイナリ側の実装が持つ。
/// こうしておくと、**`scopegrep-core` は `no_std`・依存 0 のまま**、
/// 正規表現のような重い照合を外から差し込める（ADR 0002）。
///
/// 一致は**1行ごと**に見る。値は行単位で持つ設計なので、
/// 複数行スカラーを跨いだ一致は起きない。
pub trait Matcher: core::fmt::Debug {
    /// `text` の中で一致が始まる位置を、**先頭からの文字数**（0 始まり）で返す。
    ///
    /// 🔴 バイト位置ではなく**文字数**である。ここを取り違えると、
    /// 非 ASCII を含む行だけ桁がずれる。一致しなければ `None`。
    fn find(&self, text: &str) -> Option<usize>;
}
